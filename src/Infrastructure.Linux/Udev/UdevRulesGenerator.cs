using System.Globalization;
using System.Text;

namespace RigForge.Infrastructure.Linux.Udev;

/// <summary>
/// Generates udev rules that give the logged-in user (systemd-logind "uaccess") access to the supported USB
/// controllers, so the daemon can run without root. Install as /etc/udev/rules.d/60-rigforge.rules, then run
/// <c>sudo udevadm control --reload-rules &amp;&amp; sudo udevadm trigger</c>.
/// </summary>
public static class UdevRulesGenerator
{
    public const string RecommendedPath = "/etc/udev/rules.d/60-rigforge.rules";

    /// <summary>Returns the rules with LF line endings regardless of the OS the generator runs on.</summary>
    public static string Generate(IEnumerable<(int VendorId, IReadOnlyCollection<int>? ProductIds, string Description)> devices)
    {
        var builder = new StringBuilder();
        Line(builder, "# RigForge: user-mode access to RGB / cooling controllers (generated by rigforge-scan udev).");
        Line(builder, "# hidraw = HID control channel, usb = bulk endpoints (AIO screens via libusb).");
        Line(builder);

        foreach (var (vendorId, productIds, description) in devices)
        {
            var vendor = vendorId.ToString("x4", CultureInfo.InvariantCulture);
            var products = productIds is { Count: > 0 }
                ? $", ATTRS{{idProduct}}==\"{string.Join('|', productIds.Order().Select(p => p.ToString("x4", CultureInfo.InvariantCulture)))}\""
                : string.Empty;

            Line(builder, $"# {description}");
            Line(builder, $"KERNEL==\"hidraw*\", SUBSYSTEM==\"hidraw\", ATTRS{{idVendor}}==\"{vendor}\"{products}, TAG+=\"uaccess\"");
            Line(builder, $"SUBSYSTEM==\"usb\", ATTRS{{idVendor}}==\"{vendor}\"{products}, TAG+=\"uaccess\"");
            Line(builder);
        }

        Line(builder, "# Optional: allow members of group \"rigforge\" to drive motherboard PWM outputs through hwmon.");
        Line(builder, "# ACTION==\"add\", SUBSYSTEM==\"hwmon\", RUN+=\"/bin/sh -c 'chgrp rigforge /sys%p/pwm* && chmod g+w /sys%p/pwm*'\"");

        return builder.ToString();
    }

    private static void Line(StringBuilder builder, string text = "") => builder.Append(text).Append('\n');
}
